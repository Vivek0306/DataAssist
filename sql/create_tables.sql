    PS_SUPPKEY	BIGINT NOT NULL,
    PS_AVAILQTY	BIGINT NOT NULL,
    PS_SUPPLYCOST	NUMERIC(12,2) NOT NULL,
    PS_COMMENT	VARCHAR(199),
