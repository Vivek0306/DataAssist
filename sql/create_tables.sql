);

CREATE TABLE IF NOT EXISTS retail_raw.ORDERS(
    O_ORDERKEY	BIGINT PRIMARY KEY,
    O_CUSTKEY	BIGINT,
    O_ORDERSTATUS	VARCHAR(1),
    O_TOTALPRICE	NUMERIC(12,2),
